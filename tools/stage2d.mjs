import { resolve, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const dir = resolve(here, '..')
const { launchBrowser } = await import(pathToFileURL(resolve('D:/deepseek/杂项/dsh-game-studio/src/playtest.ts')).href)
const { browser } = await launchBrowser()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []
page.on('pageerror', e => errors.push(String(e.message ?? e)))
await page.goto(pathToFileURL(resolve(dir, 'dist/index.html')).href)
await page.waitForFunction('typeof window.__stage === "function"')
await page.keyboard.press('Enter')
await page.waitForTimeout(600)
await page.evaluate(`(() => { const sh = window.__shop(); sh.level = 0; sh.squad=[0,1,2,3,4]; sh.rats=[{line:'tank',tier:2,mod:''},{line:'shot',tier:2,mod:''},{line:'blade',tier:3,mod:''},{line:'hex',tier:2,mod:''},{line:'care',tier:2,mod:''}]; window.__shopNext(); if (window.__gameState().phaseRaw==='brief') {} })()`)
await page.waitForTimeout(300)
const s0 = await page.evaluate('window.__stage()')
await page.evaluate('window.__setTimeScale(2)')
const t0 = Date.now()
while (Date.now() - t0 < 9000) { await page.evaluate('window.__autoplay(window.__gameState())'); await page.waitForTimeout(120) }
const s1 = await page.evaluate('window.__stage()')
const fmt = (st) => st.units.filter(Boolean).map(u => `${u.name}@${u.x},${u.y}×${u.scale}`).join(' | ') + '  ||  ' + st.foes.map(f => `${f.name}@${f.x},${f.y}×${f.scale}`).join(' | ')
console.log('floor', JSON.stringify(s0.floor))
console.log('t0', fmt(s0))
console.log('t9', fmt(s1))
console.log('errors', errors)
await browser.close()
if (errors.length) process.exit(1)
