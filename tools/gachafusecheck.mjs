import { resolve, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const dir = resolve(here, '..')
const { launchBrowser } = await import(pathToFileURL(resolve('D:/deepseek/杂项/dsh-game-studio/src/playtest.ts')).href)
const { browser } = await launchBrowser()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []
page.on('pageerror', e => errors.push(String(e.message ?? e)))
await page.goto(pathToFileURL(resolve(dir, 'dist/index.html')).href)
await page.waitForFunction('typeof window.__gachaSim === "function"')
await page.keyboard.press('Enter')
await page.waitForTimeout(400)
const g = await page.evaluate('window.__gachaSim(20000)')
const f = await page.evaluate('window.__fuseSim(5000)')
console.log('gacha', JSON.stringify(g))
console.log('fuse', JSON.stringify(f))
console.log('errors', errors)
await browser.close()
if (errors.length) process.exit(1)
