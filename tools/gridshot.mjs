import { resolve, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const here = dirname(fileURLToPath(import.meta.url))
const dir = resolve(here, '..')
const { launchBrowser } = await import(pathToFileURL(resolve('D:/deepseek/杂项/dsh-game-studio/src/playtest.ts')).href)
const { browser } = await launchBrowser()
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []
page.on('pageerror', e => errors.push(String(e.message ?? e)))
await page.goto(pathToFileURL(resolve(dir, 'dist/index.html')).href)
await page.waitForFunction('typeof window.__grid === "function"')
await page.keyboard.press('Enter')
await page.waitForTimeout(600)
await page.evaluate(`(() => { const sh = window.__shop(); sh.level = 0; sh.squad=[0,1,2,3,4]; sh.rats=[{line:'tank',tier:2,mod:''},{line:'shot',tier:2,mod:''},{line:'blade',tier:2,mod:''},{line:'hex',tier:2,mod:''},{line:'care',tier:2,mod:''}]; window.__shopNext(); })()`)
await page.waitForTimeout(400)
const on = await page.evaluate('window.__grid(true)')
const s = await page.evaluate('window.__stage()')
const fmt = (st) => st.units.filter(Boolean).map(u => `${u.name}@${u.x},${u.y}`).join(' | ')
console.log('grid', on, 'floor', JSON.stringify(s.floor))
console.log('formation positions:', fmt(s))
await page.screenshot({ path: resolve(dir, 'tools', '_grid.png') })
console.log('errors', errors)
await browser.close()
if (errors.length) process.exit(1)
