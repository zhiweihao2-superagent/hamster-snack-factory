def main():
    output = Path(__file__).resolve().parent / 'icons'
    output.mkdir(exist_ok=True)
    for name, rows in ICONS.items():
        if len(rows) != 16 or any(len(row) != 16 for row in rows):
            raise ValueError(f'{name} must have exactly 16 rows of 16 pixels: {[len(row) for row in rows]}')
        image = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
        for y, row in enumerate(rows):
            for x, pixel in enumerate(row):
                colour = PALETTE[pixel]
                if colour is not None:
                    image.putpixel((x, y), (*colour, 255))
        image.save(output / f'{name}.png')
        image.resize((32, 32), Image.Resampling.NEAREST).save(output / f'{name}_32.png')


if __name__ == '__main__':
    main()